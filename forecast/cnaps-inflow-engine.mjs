import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const rows = JSON.parse(fs.readFileSync(path.join(__dirname,'cnaps-inflow-history.json'),'utf8')).rows;
const customerOpportunities = JSON.parse(fs.readFileSync(path.join(__dirname,'cnaps-customer-opportunities.json'),'utf8'));
const AS_OF = '2026-08-11';
const TODAY = { inflow: 24.00, large: 23.60, instant: 0.40, unmatched: 2.40, confirmed: 21.60 };
const SEGMENTS = ['recurring','large','instant'];
const LABELS = { recurring:'经常性客户', large:'大额客户', instant:'即时转账' };

function median(a){const x=[...a].sort((a,b)=>a-b),m=Math.floor(x.length/2);return x.length%2?x[m]:(x[m-1]+x[m])/2;}
function quantile(a,q){const x=[...a].sort((a,b)=>a-b),p=(x.length-1)*q,lo=Math.floor(p),hi=Math.ceil(p);return lo===hi?x[lo]:x[lo]+(x[hi]-x[lo])*(p-lo);}
function mulberry32(seed){return function(){let t=seed+=0x6D2B79F5;t=Math.imul(t^(t>>>15),t|1);t^=t+Math.imul(t^(t>>>7),t|61);return ((t^(t>>>14))>>>0)/4294967296;};}

function rangeSeries(days) {
  const cutoff = new Date(new Date(AS_OF+'T00:00:00+08:00').getTime() - days*86400000).toISOString().slice(0,10);
  return rows.filter(r => r.date > cutoff && r.date <= AS_OF);
}
function summarize(series) {
  const avg = (key) => series.reduce((s,r)=>s+Number(r[key]||0),0) / Math.max(1,series.length);
  return {
    days: series.length,
    avg_total: Number(avg('total').toFixed(2)),
    avg_confirmed: Number(avg('confirmed').toFixed(2)),
    avg_unmatched: Number(avg('unmatched').toFixed(2)),
    avg_recurring: Number(avg('recurring').toFixed(2)),
    avg_large: Number(avg('large').toFixed(2)),
    avg_instant: Number(avg('instant').toFixed(2)),
    series: series.map(r=>({ date:r.date, total:Number(r.total.toFixed(2)), confirmed:Number(r.confirmed.toFixed(2)), unmatched:Number(r.unmatched.toFixed(2)) }))
  };
}
function nextBusinessDays(n) {
  const out=[]; let d=new Date(AS_OF+'T00:00:00+08:00');
  while(out.length<n){d=new Date(d.getTime()+86400000);if(d.getDay()!==0&&d.getDay()!==6)out.push(`${d.getFullYear()}-${String(d.getMonth()+1).padStart(2,'0')}-${String(d.getDate()).padStart(2,'0')}`);}
  return out;
}
function forecast(days=5) {
  const recent=rows.slice(-60);
  const byWeekday={};
  for(const r of recent){if(!byWeekday[r.weekday])byWeekday[r.weekday]=[];byWeekday[r.weekday].push(r);}
  const rand=mulberry32(20260811);
  const dates=nextBusinessDays(days);
  const paths=Array.from({length:600},()=>[]);
  const dayForecasts=[];
  dates.forEach((date)=>{
    const wd=new Date(date+'T00:00:00+08:00').getDay();
    const pool=byWeekday[wd]||recent;
    const medians={};
    const residuals={};
    for(const seg of SEGMENTS){
      const vals=pool.map(r=>Number(r[seg]||0));
      medians[seg]=median(vals);
      residuals[seg]=vals.map(v=>v-medians[seg]);
    }
    const samples=Array.from({length:600},()=>SEGMENTS.reduce((s,seg)=>s+medians[seg]+residuals[seg][Math.floor(rand()*residuals[seg].length)],0));
    const p50=quantile(samples,.5),p72=quantile(samples,.72),p95=quantile(samples,.95);
    dayForecasts.push({date,weekday:['周日','周一','周二','周三','周四','周五','周六'][wd],p50:Number(p50.toFixed(2)),p72:Number(p72.toFixed(2)),p95:Number(p95.toFixed(2))});
    paths.forEach((p,i)=>p.push(samples[i]));
  });
  const totals=paths.map(p=>p.reduce((a,b)=>a+b,0));
  const segAvg=SEGMENTS.reduce((o,seg)=>{o[seg]=Number((recent.reduce((s,r)=>s+Number(r[seg]||0),0)/recent.length).toFixed(2));return o;},{});
  const totalAvg=SEGMENTS.reduce((s,seg)=>s+segAvg[seg],0);
  const shares=SEGMENTS.map(seg=>({key:seg,label:LABELS[seg],share:Number((segAvg[seg]/totalAvg*100).toFixed(1)),avg:segAvg[seg]}));
  return {
    days, dates, daily: dayForecasts,
    total: {p50:Number(quantile(totals,.5).toFixed(2)),p72:Number(quantile(totals,.72).toFixed(2)),p95:Number(quantile(totals,.95).toFixed(2))},
    segments: shares,
    confidence: 0.71,
    model_version:'cnaps-inflow-v0.1-weekday-bootstrap',
    note:'基于 6 个月沙盘来账历史、星期效应与残差 bootstrap；不是生产预测。'
  };
}

const s3=summarize(rangeSeries(90));
const s6=summarize(rangeSeries(180));
const f=forecast(5);
const payload={
  as_of:AS_OF,
  today:TODAY,
  ranges:{'3M':s3,'6M':s6},
  forecast:f,
  customers: customerOpportunities,
  sources:'sandbox CNAPS daily inflow history · 128 business days',
  generated_at:new Date().toISOString()
};
fs.writeFileSync(path.join(__dirname,'cnaps-inflow-snapshot.js'),`/* generated by cnaps-inflow-engine.mjs */\nwindow.CNAPS_INFLOW_TREND = ${JSON.stringify(payload,null,2)};\n`);
